import { useState, useEffect } from 'react';
import { useSearchParams } from 'react-router-dom';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import {
  Box, Typography, Grid, TextField, MenuItem, Button, Alert, Paper, IconButton,
  Tooltip, Menu, Card, CardContent, Drawer, Divider, Chip, Snackbar, CircularProgress,
  Dialog, DialogTitle, DialogContent, DialogActions, FormControlLabel, Checkbox,
  Table, TableHead, TableRow, TableCell, TableBody,
} from '@mui/material';
import {
  Search, Close, Refresh, ArrowDropDown, InsertDriveFile, Description,
  CheckCircle, Schedule, Download, VerifiedUser, PictureAsPdf, Add,
} from '@mui/icons-material';
import { SectionTable } from 'shared';
import { api } from '../services/api';
import { useAuth } from '../contexts/AuthContext';

const REPORT_ROLES = ['CCO', 'TENANT_ADMIN'];

const SECTION_OPTIONS = [
  { key: 'summary', label: 'Executive Summary' },
  { key: 'attention', label: 'Board Attention' },
  { key: 'risk', label: 'Risk Profile' },
  { key: 'coverage', label: 'Control Coverage' },
  { key: 'returns', label: 'Returns' },
  { key: 'findings', label: 'Findings' },
  { key: 'sanctions', label: 'Sanctions' },
];

const COLUMNS = [
  { id: 'period', label: 'Period', minWidth: 220, sortable: false },
  { id: 'status', label: 'Status', minWidth: 130, sortable: false },
  { id: 'score', label: 'Score', minWidth: 100, sortable: false },
  { id: 'generatedByName', label: 'Generated By', minWidth: 160, sortable: false },
  { id: 'generatedAt', label: 'Generated', minWidth: 160, sortable: false },
];

const STATUS_META = {
  DRAFT: { color: 'warning', label: 'Draft', icon: <Schedule fontSize="small" /> },
  SIGNED_OFF: { color: 'success', label: 'Signed off', icon: <VerifiedUser fontSize="small" /> },
};

function fmtDate(iso) {
  if (!iso) return '—';
  const d = new Date(iso);
  return d.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
}

function KpiCard({ kpi, onSelect, onDrill }) {
  const [anchor, setAnchor] = useState(null);
  const entries = Object.entries(kpi.breakdown || {}).sort((a, b) => b[1] - a[1]).slice(0, 10);
  return (
    <Card variant="outlined" onClick={() => onSelect(kpi.key)}
      sx={{ cursor: 'pointer', borderLeft: `4px solid ${kpi.color}`, '&:hover': { boxShadow: 1 } }}>
      <CardContent sx={{ py: 1.5, '&:last-child': { pb: 1.5 } }}>
        <Box sx={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between' }}>
          <Box sx={{ display: 'flex', alignItems: 'center', gap: 0.75 }}>
            <Box sx={{ color: kpi.color, opacity: 0.5 }}>{kpi.icon}</Box>
            <Typography variant="caption" color="text.secondary" sx={{ fontWeight: 600 }}>{kpi.label}</Typography>
          </Box>
          {entries.length > 0 && (
            <IconButton size="small" aria-label={`${kpi.label} breakdown`}
              onMouseDown={(e) => e.stopPropagation()}
              onClick={(e) => { e.stopPropagation(); setAnchor(e.currentTarget); }}>
              <ArrowDropDown fontSize="small" />
            </IconButton>
          )}
        </Box>
        <Typography variant="h4" sx={{ fontWeight: 700, color: kpi.color }}>{kpi.value}</Typography>
        <Menu anchorEl={anchor} open={!!anchor} onClose={() => setAnchor(null)} onClick={(e) => e.stopPropagation()}>
          {entries.map(([label, count]) => (
            <MenuItem key={label} dense onClick={() => { setAnchor(null); onDrill(kpi.key, label); }}>
              <Box sx={{ display: 'flex', justifyContent: 'space-between', gap: 3, width: '100%' }}>
                <span>{label}</span>
                <span style={{ color: '#718096' }}>{count}</span>
              </Box>
            </MenuItem>
          ))}
        </Menu>
      </CardContent>
    </Card>
  );
}

const today = new Date();
const iso = (d) => d.toISOString().slice(0, 10);
const quarterStart = () => {
  const q = Math.floor(today.getMonth() / 3);
  return iso(new Date(today.getFullYear(), q * 3, 1));
};
const yearStart = () => iso(new Date(today.getFullYear(), 0, 1));

function GenerateDialog({ open, onClose, onGenerated, canGenerate }) {
  const [preset, setPreset] = useState('quarter');
  const [from, setFrom] = useState(quarterStart());
  const [to, setTo] = useState(iso(today));
  const [sections, setSections] = useState(SECTION_OPTIONS.map(s => s.key));
  const [error, setError] = useState('');

  useEffect(() => {
    if (preset === 'month') setFrom(iso(new Date(today.getFullYear(), today.getMonth(), 1)));
    else if (preset === 'quarter') setFrom(quarterStart());
    else if (preset === 'year') setFrom(yearStart());
  }, [preset]);

  const { data: preview, isLoading } = useQuery({
    queryKey: ['board-pack-preview', from, to, sections],
    queryFn: ({ signal }) => api.reports.preview(from, to, sections, { signal }),
    enabled: open && !!from && !!to,
  });

  const generate = useMutation({
    mutationFn: () => api.reports.generate({ periodFrom: from, periodTo: to, sections }),
    onSuccess: (pack) => { onGenerated(pack); onClose(); },
    onError: (e) => setError(e.message),
  });

  const valid = sections.length > 0 && from && to && from <= to;

  return (
    <Dialog open={open} onClose={onClose} maxWidth="sm" fullWidth>
      <DialogTitle>Generate Board Pack</DialogTitle>
      <DialogContent dividers>
        {error && <Alert severity="error" sx={{ mb: 2 }}>{error}</Alert>}
        <TextField select size="small" fullWidth label="Period" value={preset}
          onChange={(e) => setPreset(e.target.value)} sx={{ mb: 2 }}>
          <MenuItem value="month">This month</MenuItem>
          <MenuItem value="quarter">This quarter</MenuItem>
          <MenuItem value="year">This year</MenuItem>
          <MenuItem value="custom">Custom range</MenuItem>
        </TextField>
        <Box sx={{ display: 'flex', gap: 2, mb: 2 }}>
          <TextField size="small" type="date" label="From" value={from} InputLabelProps={{ shrink: true }}
            onChange={(e) => { setFrom(e.target.value); setPreset('custom'); }} fullWidth />
          <TextField size="small" type="date" label="To" value={to} InputLabelProps={{ shrink: true }}
            onChange={(e) => { setTo(e.target.value); setPreset('custom'); }} fullWidth />
        </Box>
        <Typography variant="caption" color="text.secondary" sx={{ fontWeight: 600, textTransform: 'uppercase' }}>
          Sections
        </Typography>
        <Box sx={{ display: 'grid', gridTemplateColumns: '1fr 1fr', mt: 0.5 }}>
          {SECTION_OPTIONS.map((s) => (
            <FormControlLabel key={s.key} control={
              <Checkbox size="small" checked={sections.includes(s.key)}
                onChange={(e) => setSections(prev => e.target.checked ? [...prev, s.key] : prev.filter(k => k !== s.key))} />
            } label={<Typography variant="body2">{s.label}</Typography>} />
          ))}
        </Box>

        <Divider sx={{ my: 2 }} />
        <Typography variant="body2" color="text.secondary" sx={{ mb: 1 }}>
          Preview {preview ? `— ${preview.institutionName}` : ''}
        </Typography>
        {isLoading ? <CircularProgress size={20} /> : preview && (
          <Box sx={{ display: 'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap: 1 }}>
            <Stat label="Compliance Score" value={preview.metrics?.complianceScore != null ? `${preview.metrics.complianceScore}%` : '—'} />
            <Stat label="Obligations" value={preview.metrics?.obligationsApplicable ?? 0} />
            <Stat label="High Risk" value={preview.metrics?.obligationsHighRisk ?? 0} />
            <Stat label="Control Coverage" value={`${preview.metrics?.controlCoverage ?? 0}%`} />
            <Stat label="Returns On Time" value={`${preview.metrics?.returnsOnTimePct ?? 0}%`} />
            <Stat label="Open Findings" value={preview.metrics?.findingsOpen ?? 0} />
          </Box>
        )}
      </DialogContent>
      <DialogActions>
        <Button onClick={onClose}>Cancel</Button>
        <Button variant="contained" disabled={!valid || !canGenerate || generate.isPending}
          onClick={() => generate.mutate()}
          startIcon={generate.isPending ? <CircularProgress size={16} color="inherit" /> : <PictureAsPdf />}>
          Generate Draft
        </Button>
      </DialogActions>
    </Dialog>
  );
}

function Stat({ label, value }) {
  return (
    <Box sx={{ border: '1px solid #E2E8F0', borderRadius: 1, p: 1 }}>
      <Typography variant="caption" color="text.secondary" sx={{ fontWeight: 600 }}>{label}</Typography>
      <Typography variant="body1" sx={{ fontWeight: 700 }}>{value}</Typography>
    </Box>
  );
}

export default function ReportsPage() {
  const { user } = useAuth();
  const canGenerate = REPORT_ROLES.includes(user?.role);
  const canSignOff = user?.role === 'CCO';
  const qc = useQueryClient();
  const [searchParams, setSearchParams] = useSearchParams();
  const [statusFilter, setStatusFilter] = useState(searchParams.get('status') || 'All');
  const [page, setPage] = useState(Number(searchParams.get('page') || 0));
  const [size, setSize] = useState(Number(searchParams.get('size') || 20));
  const [selected, setSelected] = useState(null);
  const [genOpen, setGenOpen] = useState(false);
  const [signOffOpen, setSignOffOpen] = useState(false);
  const [signOffNote, setSignOffNote] = useState('');
  const [toast, setToast] = useState(null);

  useEffect(() => {
    const p = {};
    if (statusFilter !== 'All') p.status = statusFilter;
    if (page) p.page = String(page);
    if (size !== 20) p.size = String(size);
    setSearchParams(p, { replace: true });
  }, [statusFilter, page, size, setSearchParams]);

  const { data, isLoading, error, refetch } = useQuery({
    queryKey: ['board-packs', page, size],
    queryFn: ({ signal }) => api.reports.list({ page, size }, { signal }),
    placeholderData: (prev) => prev,
  });

  const rows = data?.content || [];
  const total = data?.totalElements ?? 0;
  const hasFilters = statusFilter !== 'All';

  const filtered = statusFilter === 'All' ? rows : rows.filter(r => r.status === statusFilter);
  const drafts = rows.filter(r => r.status === 'DRAFT').length;
  const signed = rows.filter(r => r.status === 'SIGNED_OFF').length;
  const lastSigned = rows.find(r => r.status === 'SIGNED_OFF');

  const signOff = useMutation({
    mutationFn: () => api.reports.signOff(selected.boardPackId, signOffNote),
    onSuccess: () => {
      setSignOffOpen(false); setSignOffNote(''); setSelected(null);
      qc.invalidateQueries(['board-packs']); refetch();
      setToast({ severity: 'success', message: 'Board pack signed off.' });
    },
    onError: (e) => setToast({ severity: 'error', message: e.message }),
  });

  function download(id) {
    api.reports.download(id).catch(e => setToast({ severity: 'error', message: e.message }));
  }

  const kpis = [
    { key: 'total', label: 'Total Packs', value: total, color: '#2B6CB0', icon: <Description sx={{ fontSize: 20 }} /> },
    { key: 'drafts', label: 'Drafts', value: drafts, color: '#DD6B20', icon: <Schedule sx={{ fontSize: 20 }} /> },
    { key: 'signed', label: 'Signed Off', value: signed, color: '#2C7A7B', icon: <CheckCircle sx={{ fontSize: 20 }} /> },
    { key: 'last', label: 'Last Sign-off', value: lastSigned ? fmtDate(lastSigned.signedOffAt) : '—', color: '#805AD5', icon: <VerifiedUser sx={{ fontSize: 20 }} /> },
  ];

  function onKpiSelect(key) {
    setPage(0);
    if (key === 'drafts') setStatusFilter('DRAFT');
    else if (key === 'signed') setStatusFilter('SIGNED_OFF');
    else setStatusFilter('All');
  }

  const columns = COLUMNS.map(c => ({
    ...c,
    render: c.id === 'period' ? (r) => `${r.periodFrom} → ${r.periodTo}`
      : c.id === 'status' ? (r) => {
          const meta = STATUS_META[r.status] || { color: 'default', label: r.status };
          return <Chip size="small" color={meta.color} label={meta.label} sx={{ height: 22, borderRadius: '4px' }} />;
        }
      : c.id === 'score' ? (r) => (r.complianceScore != null ? `${r.complianceScore}%` : '—')
      : undefined,
  }));

  return (
    <Box>
      <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', mb: 0.5 }}>
        <Box>
          <Typography variant="h4">Reports</Typography>
          <Typography variant="body2" color="text.secondary">
            Board packs — generate, review and sign off the compliance report for the board
          </Typography>
        </Box>
        <Box sx={{ display: 'flex', gap: 1 }}>
          <Tooltip title="Refresh"><IconButton onClick={() => refetch()}><Refresh /></IconButton></Tooltip>
          {canGenerate && (
            <Button variant="contained" startIcon={<Add />} onClick={() => setGenOpen(true)}>Generate Board Pack</Button>
          )}
        </Box>
      </Box>

      {error && <Alert severity="error" sx={{ mb: 2 }}>{error.message}</Alert>}

      <Grid container spacing={2} sx={{ mb: 2 }}>
        {kpis.map((k) => (
          <Grid key={k.key} size={{ xs: 6, md: 3 }}>
            <KpiCard kpi={k} onSelect={onKpiSelect} onDrill={() => {}} />
          </Grid>
        ))}
      </Grid>

      <Paper sx={{ p: 2, mb: 2, display: 'flex', gap: 1.5, flexWrap: 'wrap', alignItems: 'center' }}>
        <TextField select size="small" value={statusFilter} label="Status"
          onChange={(e) => { setStatusFilter(e.target.value); setPage(0); }} sx={{ minWidth: 160 }}>
          <MenuItem value="All">All</MenuItem>
          <MenuItem value="DRAFT">Draft</MenuItem>
          <MenuItem value="SIGNED_OFF">Signed off</MenuItem>
        </TextField>
        {hasFilters && <Button size="small" startIcon={<Close />} onClick={() => { setStatusFilter('All'); setPage(0); }}>Clear</Button>}
      </Paper>

      <SectionTable
        columns={columns}
        rows={filtered}
        total={total}
        page={page}
        size={size}
        loading={isLoading}
        error={error}
        sortField=""
        sortDir="asc"
        onSort={() => {}}
        onPage={setPage}
        onSize={(s) => { setSize(s); setPage(0); }}
        onRowClick={(row) => setSelected(row)}
        rowKey={(r) => r.boardPackId}
        emptyMessage="No board packs yet. Generate one to get started."
      />

      <GenerateDialog open={genOpen} canGenerate={canGenerate} onClose={() => setGenOpen(false)}
        onGenerated={(pack) => { qc.invalidateQueries(['board-packs']); refetch(); setToast({ severity: 'success', message: 'Board pack generated.' }); if (pack) setSelected(pack); }} />

      {/* Detail drawer */}
      <Drawer anchor="right" open={!!selected} onClose={() => setSelected(null)} PaperProps={{ sx: { width: 480, p: 3 } }}>
        {selected && (
          <Box>
            <Box sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', mb: 2 }}>
              <Typography variant="h6" sx={{ fontWeight: 700 }}>Board Pack</Typography>
              <IconButton onClick={() => setSelected(null)}><Close /></IconButton>
            </Box>
            <Chip size="small" color={STATUS_META[selected.status]?.color} label={STATUS_META[selected.status]?.label}
              sx={{ height: 22, borderRadius: '4px', mb: 2 }} />
            <Box sx={{ display: 'grid', gridTemplateColumns: '140px 1fr', gap: '6px 16px', mb: 2 }}>
              <Field label="Period" value={`${selected.periodFrom} → ${selected.periodTo}`} />
              <Field label="Compliance Score" value={selected.complianceScore != null ? `${selected.complianceScore}%` : '—'} />
              <Field label="Generated By" value={selected.generatedByName || '—'} />
              <Field label="Generated" value={fmtDate(selected.generatedAt)} />
              {selected.status === 'SIGNED_OFF' && <>
                <Field label="Signed Off By" value={selected.signedOffByName || '—'} />
                <Field label="Signed Off" value={fmtDate(selected.signedOffAt)} />
              </>}
              <Field label="File" value={selected.fileName || '—'} />
            </Box>
            {selected.signOffNote && (
              <Box sx={{ bgcolor: '#F7FAFC', borderRadius: 1, p: 1.5, mb: 2 }}>
                <Typography variant="caption" color="text.secondary" sx={{ fontWeight: 600 }}>Sign-off note</Typography>
                <Typography variant="body2">{selected.signOffNote}</Typography>
              </Box>
            )}
            <Box sx={{ display: 'flex', gap: 1, mt: 2 }}>
              <Button variant="outlined" startIcon={<Download />} onClick={() => download(selected.boardPackId)}>Download PDF</Button>
              {canSignOff && selected.status === 'DRAFT' && (
                <Button variant="contained" startIcon={<VerifiedUser />} onClick={() => setSignOffOpen(true)}>Sign Off</Button>
              )}
            </Box>
          </Box>
        )}
      </Drawer>

      {/* Sign-off dialog */}
      <Dialog open={signOffOpen} onClose={() => setSignOffOpen(false)} maxWidth="xs" fullWidth>
        <DialogTitle>Sign Off Board Pack</DialogTitle>
        <DialogContent dividers>
          <Typography variant="body2" color="text.secondary" sx={{ mb: 2 }}>
            Signing off removes the DRAFT watermark and locks the pack. Generate a new one to make changes.
          </Typography>
          <TextField fullWidth multiline minRows={2} label="Note (optional)" value={signOffNote}
            onChange={(e) => setSignOffNote(e.target.value)} />
        </DialogContent>
        <DialogActions>
          <Button onClick={() => setSignOffOpen(false)}>Cancel</Button>
          <Button variant="contained" disabled={signOff.isPending} onClick={() => signOff.mutate()}>
            {signOff.isPending ? 'Signing…' : 'Confirm Sign Off'}
          </Button>
        </DialogActions>
      </Dialog>

      <Snackbar open={!!toast} autoHideDuration={4000} onClose={() => setToast(null)}
        anchorOrigin={{ vertical: 'bottom', horizontal: 'center' }}>
        {toast ? <Alert severity={toast.severity} onClose={() => setToast(null)}>{toast.message}</Alert> : undefined}
      </Snackbar>
    </Box>
  );
}

function Field({ label, value }) {
  return (<>
    <Typography variant="caption" color="text.secondary" sx={{ fontWeight: 600 }}>{label}</Typography>
    <Typography variant="body2">{value}</Typography>
  </>);
}